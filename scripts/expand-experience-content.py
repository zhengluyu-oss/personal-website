def sql_quote(value):
    if value is None:
        return 'NULL'
    return "'" + value.replace('\\', '\\\\').replace("'", "''").replace('\n', '\\n') + "'"


def sql_set(values):
    return ', '.join(f'{key}={sql_quote(value)}' for key, value in values.items())


